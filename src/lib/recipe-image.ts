const apostrophes = /['’ʼ`´ʻ]/g;

export function recipeImageSlug(title: string) {
  return title
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(apostrophes, "")
    .toLocaleLowerCase("nl-NL")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

